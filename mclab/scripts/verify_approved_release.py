#!/usr/bin/env python3
"""Fail closed before publishing if generated MCLab data regresses from the approved baseline.

The baseline is a reviewed lockfile, NEVER regenerated by the deployment workflow.
For intentional edits, review source changes and update only the affected baseline entries.
"""
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
BASELINE = ROOT / "quality" / "approved-baseline.json"
OUTPUT = ROOT / "_site"
GROUPS = ("people", "publications", "projects", "researchTopics", "gallery", "news")

def read_data(path):
    raw = path.read_text(encoding="utf-8")
    marker = "window.MCLAB_DATA = "
    if marker not in raw:
        raise ValueError(f"Missing MCLAB_DATA assignment: {path}")
    return json.loads(raw.split(marker, 1)[1].strip().rstrip(";"))

def check():
    approved = json.loads(BASELINE.read_text(encoding="utf-8"))
    data = read_data(OUTPUT / "data" / "site-data.js")
    problems = []
    for group in GROUPS:
        records = data.get(group, [])
        ids = [record.get("id") for record in records]
        lookup = {record.get("id"): record for record in records}
        if len(ids) != len(set(ids)):
            problems.append(f"{group}: duplicate IDs")
        if len(records) < approved["minimumCounts"][group]:
            problems.append(f"{group}: record count {len(records)} below approved {approved['minimumCounts'][group]}")
        for key in ids:
            if key not in approved["requiredIds"][group]:
                problems.append(f"{group}: unapproved new/reappearing item: {key}")
        for key in approved["requiredIds"][group]:
            if key not in lookup:
                problems.append(f"{group}: approved item missing: {key}")
        for key in approved.get("forbiddenIds", {}).get(group, []):
            if key in lookup:
                problems.append(f"{group}: deleted/hidden item reappeared: {key}")
        for key, fields in approved.get("protected", {}).get(group, {}).items():
            record = lookup.get(key)
            if record is None:
                continue
            for field, value in fields.items():
                if record.get(field) != value:
                    problems.append(f"{group}/{key}: approved {field} changed")
    for field, value in approved["protected"]["pi"].items():
        if data.get("pi", {}).get(field) != value:
            problems.append(f"PI profile: approved {field} changed")
    files = {str(p.relative_to(OUTPUT)) for p in OUTPUT.rglob("*") if p.is_file()}
    for group, field in (("people", "photo"), ("researchTopics", "image"),
                         ("gallery", "image"), ("news", "image")):
        for record in data.get(group, []):
            path = record.get(field, "")
            if path and not path.startswith(("https://", "http://")) and path not in files:
                problems.append(f"{group}/{record.get('id')}: image missing: {path}")
    photo = data.get("pi", {}).get("photo", "")
    if not photo or photo not in files:
        problems.append(f"PI portrait missing: {photo}")
    for video in approved["requiredVideos"]:
        if video not in files:
            problems.append(f"Required research video missing: {video}")
    for page in ("index", "people", "professor", "research", "publications",
                 "projects", "news", "join"):
        html = OUTPUT / (page + ".html")
        if not html.is_file():
            problems.append(f"Page missing: {html.name}")
            continue
        text = html.read_text(encoding="utf-8")
        for asset in ("data/site-data.js", "assets/js/app.js", "assets/css/style.css"):
            if asset not in text:
                problems.append(f"{html.name}: missing {asset} reference")
    if problems:
        print("BLOCKED: MCLab approved baseline check failed:", file=sys.stderr)
        for problem in problems:
            print(" - " + problem, file=sys.stderr)
        print("Do not publish. Correct the source or explicitly review a baseline change.", file=sys.stderr)
        return 1
    print("PASS: approved content, protected records, pages, images and videos checked.")
    return 0

if __name__ == "__main__":
    try:
        sys.exit(check())
    except (OSError, ValueError, KeyError, TypeError) as exc:
        print(f"BLOCKED: unable to validate deployment: {exc}", file=sys.stderr)
        sys.exit(1)
