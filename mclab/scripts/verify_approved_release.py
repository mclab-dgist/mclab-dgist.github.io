#!/usr/bin/env python3
"""Fail closed before publishing if generated MCLab data regresses from the approved baseline.

The baseline is a reviewed lockfile, NEVER regenerated by the deployment workflow.
For intentional edits, review source changes and update only the affected baseline entries.
"""
import copy
import hashlib
from html.parser import HTMLParser
import json
import pathlib
import sys
from urllib.parse import unquote, urlsplit

ROOT = pathlib.Path(__file__).resolve().parents[1]
BASELINE = ROOT / "quality" / "approved-baseline.json"
OUTPUT = ROOT / "_site"
GROUPS = ("people", "publications", "projects", "researchTopics", "gallery", "news")
PAGES = ("index", "people", "professor", "research", "publications", "projects", "news", "join")
ASSETS = ("data/site-data.js", "assets/js/app.js", "assets/css/style.css")

def stable_content(data):
    """Exclude only build timestamps and date-derived automatic project status."""
    stable = copy.deepcopy(data)
    for field in ("builtAt", "statusDate"):
        stable.get("config", {}).pop(field, None)
    for record in stable.get("projects", []):
        if record.get("statusMode") == "auto":
            record.pop("status", None)
    return stable

def content_differences(actual, expected, path="content"):
    """Check every field and ordered list; report locations without copying content."""
    problems = []
    if type(actual) is not type(expected):
        return [f"{path}: approved value/type changed"]
    if isinstance(expected, dict):
        for key in expected.keys() - actual.keys():
            problems.append(f"{path}.{key}: approved field missing")
        for key in actual.keys() - expected.keys():
            problems.append(f"{path}.{key}: unapproved field added")
        for key in expected.keys() & actual.keys():
            problems.extend(content_differences(actual[key], expected[key], f"{path}.{key}"))
    elif isinstance(expected, list):
        if expected and actual and all(isinstance(r, dict) and "id" in r for r in expected + actual):
            actual_ids = [r["id"] for r in actual]
            expected_ids = [r["id"] for r in expected]
            if actual_ids != expected_ids:
                problems.append(f"{path}: approved item IDs/order changed")
            lookup = {r["id"]: r for r in actual}
            for record in expected:
                if record["id"] in lookup:
                    problems.extend(content_differences(lookup[record["id"]], record, f"{path}/{record['id']}"))
        else:
            if len(actual) != len(expected):
                problems.append(f"{path}: approved item count changed")
            for index, (left, right) in enumerate(zip(actual, expected)):
                problems.extend(content_differences(left, right, f"{path}[{index}]"))
    elif actual != expected:
        problems.append(f"{path}: approved value changed")
    return sorted(problems)

def validate_content(data, approved):
    if approved.get("schema") != 2:
        return ["Unsupported baseline schema; a reviewed schema-2 baseline is required"]
    problems = content_differences(stable_content(data), approved["content"])
    for group in GROUPS:
        ids = [record.get("id") for record in data.get(group, [])]
        if len(ids) != len(set(ids)):
            problems.append(f"{group}: duplicate IDs")
        for key in approved.get("forbiddenIds", {}).get(group, []):
            if key in ids:
                problems.append(f"{group}: deleted/hidden item reappeared: {key}")
    return problems

def validate_asset_references(text, versions, page):
    class AssetParser(HTMLParser):
        def __init__(self):
            super().__init__()
            self.references = []

        def handle_starttag(self, tag, attributes):
            attributes = dict(attributes)
            if tag == "script" and attributes.get("src"):
                self.references.append(("script", attributes["src"]))
            elif tag == "link" and "stylesheet" in (attributes.get("rel") or "").lower().split():
                if attributes.get("href"):
                    self.references.append(("link", attributes["href"]))

    parser = AssetParser()
    parser.feed(text)
    parser.close()
    problems = []
    for asset, version in versions.items():
        expected_tag = "link" if asset.endswith(".css") else "script"
        matching = [ref for tag, ref in parser.references
                    if tag == expected_tag and not urlsplit(ref).scheme
                    and not urlsplit(ref).netloc and urlsplit(ref).path == asset]
        if matching != [f"{asset}?v={version}"]:
            problems.append(f"{page}: missing, duplicate or stale content-hash reference for {asset}")
    return problems

def image_available(path, files):
    if not path:
        return False
    url = urlsplit(path)
    if url.scheme in ("http", "https") and url.netloc:
        return True  # External reachability is not a local build-file check.
    return not url.scheme and not url.netloc and unquote(url.path) in files

def read_data(path):
    raw = path.read_text(encoding="utf-8")
    marker = "window.MCLAB_DATA = "
    if marker not in raw:
        raise ValueError(f"Missing MCLAB_DATA assignment: {path}")
    return json.loads(raw.split(marker, 1)[1].strip().rstrip(";"))

def validate_output(data, approved, output):
    problems = []
    files = {str(p.relative_to(output)) for p in output.rglob("*") if p.is_file()}
    for group, field in (("people", "photo"), ("researchTopics", "image"),
                         ("gallery", "image"), ("news", "image")):
        for record in data.get(group, []):
            path = record.get(field, "")
            if path and not image_available(path, files):
                problems.append(f"{group}/{record.get('id')}: image missing: {path}")
    photo = data.get("pi", {}).get("photo", "")
    if not image_available(photo, files):
        problems.append(f"PI portrait missing: {photo}")
    for video in approved["requiredVideos"]:
        if video not in files:
            problems.append(f"Required research video missing: {video}")
    versions = {}
    for asset in ASSETS:
        path = output / asset
        if not path.is_file():
            problems.append(f"Required asset missing: {asset}")
        else:
            versions[asset] = hashlib.sha256(path.read_bytes()).hexdigest()[:12]
    for asset, expected_hash in approved.get("protectedAssets", {}).items():
        path = output / asset
        if not path.is_file() or hashlib.sha256(path.read_bytes()).hexdigest() != expected_hash:
            problems.append(f"{asset}: approved presentation asset changed")
    for page in PAGES:
        html = output / (page + ".html")
        if not html.is_file():
            problems.append(f"Page missing: {html.name}")
            continue
        text = html.read_text(encoding="utf-8")
        problems.extend(validate_asset_references(text, versions, html.name))
    return problems

def check():
    approved = json.loads(BASELINE.read_text(encoding="utf-8"))
    data = read_data(OUTPUT / "data" / "site-data.js")
    problems = validate_content(data, approved)
    problems.extend(validate_output(data, approved, OUTPUT))
    if problems:
        print("BLOCKED: MCLab approved baseline check failed:", file=sys.stderr)
        for problem in problems:
            print(" - " + problem, file=sys.stderr)
        print("Do not publish. Correct the source or explicitly review a baseline change.", file=sys.stderr)
        return 1
    print("PASS: full approved content/order, presentation assets, current cache hashes, pages, images and videos checked.")
    return 0

if __name__ == "__main__":
    try:
        sys.exit(check())
    except (OSError, ValueError, KeyError, TypeError) as exc:
        print(f"BLOCKED: unable to validate deployment: {exc}", file=sys.stderr)
        sys.exit(1)
